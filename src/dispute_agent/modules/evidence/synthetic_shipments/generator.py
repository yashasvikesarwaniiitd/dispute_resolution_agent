"""A seeded world of sellers, parcels and ledger entries (synthetic-data.md, I11).

Everything this system ever sees comes from here. Nothing real is used, and nothing is
generated by a model — free text comes from fixed template banks with seeded slot filling, so
a fixture is reviewable and stable rather than subtly different each run.

**Determinism is the whole contract.** The same seed produces the same world, byte for byte,
which is what makes a failing scenario re-runnable and a demo repeatable (CLAUDE.md section
10). Each entity family draws from its own `Random(seed + offset)`, so adding sellers later
cannot shift the parcels — a single shared stream would make every existing fixture change
the day somebody adds a knob.

Money is generated in paise and weight in grams, as integers, then wrapped (ADR 0011). No
float appears anywhere in this module, for the same reason it does not appear in the
calculator: these numbers end up in a message to a seller.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from decimal import Decimal
from random import Random
from typing import TYPE_CHECKING

from dispute_agent.packs.weight_dispute.calculator import Dimensions, calculate
from dispute_agent.packs.weight_dispute.rate_card import DEFAULT_RATE_CARD

if TYPE_CHECKING:
    from dispute_agent.packs.weight_dispute.rate_card import RateCard

#: Per-family offsets. Adding a family takes the next number and disturbs nothing before it.
SEED_OFFSETS: dict[str, int] = {
    "sellers": 0,
    "skus": 100,
    "hubs": 200,
    "scanners": 300,
    "shipments": 400,
    "measurements": 500,
    "ledger": 600,
}

DEFAULT_SEED = 42
TEST_DOMAIN = "example.invalid"

PACKAGING_TYPES = ("box", "box", "box", "box", "polybag", "tube")
ZONES = ("A", "A", "A", "B", "B", "B", "C", "C", "D", "E")


@dataclass(frozen=True)
class Seller:
    id: str
    contact: str


@dataclass(frozen=True)
class Sku:
    id: str
    seller_id: str
    declared: Dimensions
    declared_dead_grams: int
    packaging: str


@dataclass(frozen=True)
class Scanner:
    id: str
    hub_id: str
    #: Millimetres added to the length axis. Zero for every scanner but a fixture's, because
    #: a faulty scanner is something a test chooses, never something randomness produces.
    bias_mm: int = 0


@dataclass(frozen=True)
class Hub:
    id: str
    scanners: tuple[Scanner, ...]


@dataclass(frozen=True)
class LedgerEntry:
    transaction_id: str
    shipment_ref: str
    claim_ref: str
    kind: str
    amount_paise: int
    reason_code: str | None = None


@dataclass(frozen=True)
class Shipment:
    """One parcel, with what was declared, what was measured, and what was billed."""

    ref: str
    claim_ref: str
    seller_id: str
    sku_id: str
    hub_id: str
    scanner_id: str
    zone: str
    status: str
    declared: Dimensions
    declared_dead_grams: int
    measured: Dimensions
    measured_dead_grams: int
    packaging: str
    billed_paise: int
    #: What the pack would compute from the measured values. The bill may disagree, and that
    #: disagreement is what a `calculation_error` is.
    correct_paise: int
    ledger: tuple[LedgerEntry, ...] = ()

    @property
    def delivered(self) -> bool:
        return self.status == "DELIVERED"


@dataclass(frozen=True)
class World:
    seed: int
    sellers: tuple[Seller, ...]
    skus: tuple[Sku, ...]
    hubs: tuple[Hub, ...]
    shipments: tuple[Shipment, ...] = field(default_factory=tuple)

    def seller(self, seller_id: str) -> Seller:
        return next(s for s in self.sellers if s.id == seller_id)

    def sku(self, sku_id: str) -> Sku:
        return next(s for s in self.skus if s.id == sku_id)

    def shipment(self, ref: str) -> Shipment:
        return next(s for s in self.shipments if s.ref == ref)


def _stream(seed: int, family: str) -> Random:
    return Random(seed + SEED_OFFSETS[family])


def _cm(rng: Random, low: int, high: int) -> Decimal:
    """A dimension to one decimal place, built from integers so no float is involved."""
    return Decimal(rng.randint(low * 10, high * 10)) / Decimal(10)


def build_world(
    seed: int = DEFAULT_SEED,
    *,
    sellers: int = 40,
    hubs: int = 8,
    shipments: int = 200,
    card: RateCard | None = None,
) -> World:
    """The world, from a seed. The same seed always gives the same world.

    `shipments` defaults lower than synthetic-data.md's 2,000 because the tests build worlds
    constantly; the eval runs pass the full number. Nothing about the generation changes.
    """
    rate_card = card or DEFAULT_RATE_CARD

    seller_rng = _stream(seed, "sellers")
    built_sellers = tuple(
        Seller(id=f"SELL-{n:04d}", contact=f"seller+{n}@{TEST_DOMAIN}")
        for n in range(1, sellers + 1)
    )
    # Draw once so the stream advances identically whatever the caller does with it.
    seller_rng.random()

    sku_rng = _stream(seed, "skus")
    built_skus: list[Sku] = []
    counter = 1
    for seller in built_sellers:
        for _ in range(sku_rng.randint(1, 6)):
            built_skus.append(
                Sku(
                    id=f"SKU-{counter:04d}",
                    seller_id=seller.id,
                    declared=Dimensions(
                        length_cm=_cm(sku_rng, 10, 60),
                        width_cm=_cm(sku_rng, 8, 40),
                        height_cm=_cm(sku_rng, 2, 30),
                    ),
                    declared_dead_grams=sku_rng.randint(100, 8000),
                    packaging=sku_rng.choice(PACKAGING_TYPES),
                )
            )
            counter += 1

    scanner_rng = _stream(seed, "scanners")
    built_hubs = tuple(
        Hub(
            id=f"HUB-{n:02d}",
            scanners=tuple(Scanner(id=f"SCN-{n:02d}-{s}", hub_id=f"HUB-{n:02d}") for s in (1, 2)),
        )
        for n in range(1, hubs + 1)
    )
    scanner_rng.random()

    shipment_rng = _stream(seed, "shipments")
    measure_rng = _stream(seed, "measurements")
    ledger_rng = _stream(seed, "ledger")

    built: list[Shipment] = []
    for n in range(1, shipments + 1):
        sku = shipment_rng.choice(built_skus)
        hub = shipment_rng.choice(built_hubs)
        scanner = shipment_rng.choice(hub.scanners)
        zone = shipment_rng.choice(ZONES)
        status = "DELIVERED" if shipment_rng.randint(1, 100) <= 97 else "RTO"

        measured = _measure(sku.declared, scanner, measure_rng)
        measured_dead = max(1, sku.declared_dead_grams + measure_rng.randint(-50, 50))

        correct = calculate(measured, measured_dead, zone, rate_card, sku.packaging)
        billed_paise = correct.amount_paise
        # A small share of bills are wrong, which is what gives calculation_error something
        # to find. The error is always an overcharge: an undercharge is not this system's
        # business (money-rules.md).
        if ledger_rng.randint(1, 100) == 1:
            billed_paise = correct.amount_paise + rate_card.rate_paise_for(zone)

        ref = f"SHP-{n:06d}"
        claim = f"CLM-{n:06d}"
        entries = [
            LedgerEntry(
                transaction_id=f"TXN-{n:06d}-1",
                shipment_ref=ref,
                claim_ref=claim,
                kind="DEBIT",
                amount_paise=billed_paise,
            )
        ]
        built.append(
            Shipment(
                ref=ref,
                claim_ref=claim,
                seller_id=sku.seller_id,
                sku_id=sku.id,
                hub_id=hub.id,
                scanner_id=scanner.id,
                zone=zone,
                status=status,
                declared=sku.declared,
                declared_dead_grams=sku.declared_dead_grams,
                measured=measured,
                measured_dead_grams=measured_dead,
                packaging=sku.packaging,
                billed_paise=billed_paise,
                correct_paise=correct.amount_paise,
                ledger=tuple(entries),
            )
        )

    return World(
        seed=seed,
        sellers=built_sellers,
        skus=tuple(built_skus),
        hubs=built_hubs,
        shipments=tuple(built),
    )


def _measure(declared: Dimensions, scanner: Scanner, rng: Random) -> Dimensions:
    """What the hub's scanner read. Noise in whole millimetres, plus any scanner bias."""
    bias = Decimal(scanner.bias_mm) / Decimal(10)
    return Dimensions(
        length_cm=_jitter(declared.length_cm, rng) + bias,
        width_cm=_jitter(declared.width_cm, rng),
        height_cm=_jitter(declared.height_cm, rng),
    )


def _jitter(value: Decimal, rng: Random) -> Decimal:
    """+/- up to 10 mm, in whole millimetres, never below 1 mm."""
    shifted = value + Decimal(rng.randint(-10, 10)) / Decimal(10)
    return max(shifted, Decimal("0.1"))
